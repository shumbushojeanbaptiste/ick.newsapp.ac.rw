/** Translate a UI key into the current site language (English fallback). */
function t(string $key): string
{
    $lang = function_exists('current_lang') ? current_lang() : 'en';
    return $GLOBALS['I18N'][$lang][$key]
        ?? $GLOBALS['I18N']['en'][$key]
        ?? $key;
}
